#!/usr/bin/env python3
"""W4 — on-demand World Labs world generation.

Only runs when FEATURE_WORLDLABS_API=true and WORLDLABS_API_KEY is set.
W1 worlds are generated by hand in the Marble app — this script is for W4 only.

Usage:
  FEATURE_WORLDLABS_API=true uv run python scripts/generate_worlds.py --port Jeddah
"""

import argparse
import asyncio
import json
import os
import sys
from pathlib import Path

WORLDS_PATH = Path(__file__).parent.parent / "config" / "worlds.json"

PROMPTS = {
    "Jeddah": (
        "Jeddah Islamic Port container terminal with reefer yard, bonded warehouses, "
        "and truck exit lanes. Saudi Arabia Red Sea coastline. Industrial port infrastructure, "
        "cold-chain storage facilities."
    ),
    "Salalah": (
        "Port of Salalah Oman container terminal with temperature-controlled storage, "
        "reefer plugs, Salalah Free Zone logistics hub. Arabian Sea port infrastructure."
    ),
}


async def generate(port: str) -> None:
    from app.integrations.worldlabs import generate_world, poll_operation, get_world

    if not os.environ.get("FEATURE_WORLDLABS_API", "false").lower() == "true":
        print("SKIP: FEATURE_WORLDLABS_API is not true.")
        sys.exit(0)

    prompt = PROMPTS.get(port, f"{port} commercial port infrastructure.")
    print(f"Generating world for {port}...")
    operation_id = await generate_world(port, prompt)
    print(f"Operation started: {operation_id}")

    print("Polling for completion...")
    result = await poll_operation(operation_id)
    world_id = result.get("response", {}).get("name", "").split("/")[-1]
    world = await get_world(world_id)

    marble_url = world.get("world_marble_url", "")
    thumbnail_url = world.get("assets", {}).get("thumbnail_url", "")
    print(f"World ready: {marble_url}")

    # Update worlds.json
    with open(WORLDS_PATH, encoding="utf-8") as f:
        data = json.load(f)

    updated = False
    for entry in data.get("worlds", []):
        if entry["port"].lower() == port.lower() and entry["scope"] == "port":
            entry["marble_url"] = marble_url
            entry["thumbnail_url"] = thumbnail_url
            entry["source"] = "world_api"
            updated = True

    if not updated:
        data["worlds"].append({
            "id": f"{port.lower()}-w4-{world_id[:8]}",
            "port": port,
            "scope": "port",
            "title": f"{port} Port — W4 Generated",
            "marble_url": marble_url,
            "thumbnail_url": thumbnail_url,
            "source": "world_api",
            "prompt": prompt,
        })

    with open(WORLDS_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)

    print(f"Updated config/worlds.json with {port} world.")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate a World Labs world for a port")
    parser.add_argument("--port", required=True, choices=list(PROMPTS.keys()))
    args = parser.parse_args()
    asyncio.run(generate(args.port))


if __name__ == "__main__":
    main()
